#!/usr/bin/env python3
"""Generate a timed news script from a SearXNG source bundle."""

from __future__ import annotations

import argparse
import importlib
import json
import math
import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional


PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from services import prompting  # noqa: E402


def load_env_file(path: Path) -> None:
    dotenv = importlib.import_module("dotenv")
    dotenv.load_dotenv(path)


def word_count(text: str) -> int:
    return len(re.findall(r"\b[\w'-]+\b", text))


def humanize_subject(subject: str) -> str:
    cleaned = re.sub(r"\s+", " ", subject).strip()
    cleaned = re.sub(r"\bai\b", "AI", cleaned, flags=re.IGNORECASE)
    return cleaned or "this issue"


def sentence_split(text: str) -> list[str]:
    parts = re.split(r"(?<=[.!?])\s+", re.sub(r"\s+", " ", text).strip())
    return [part.strip() for part in parts if part.strip()]


def is_boilerplate(sentence: str) -> bool:
    lowered = sentence.lower()
    blocked_phrases = [
        "this voice experience is generated by ai",
        "learn more",
        "advertisement",
        "subscribe",
        "sign up",
        "cookies",
        "all rights reserved",
    ]
    return any(phrase in lowered for phrase in blocked_phrases)


def clean_source_sentences(text: str) -> list[str]:
    cleaned: list[str] = []
    for sentence in sentence_split(text):
        if is_boilerplate(sentence):
            continue
        if len(sentence.split()) < 6:
            continue
        cleaned.append(sentence)
    return cleaned


def source_label(source: dict[str, Any]) -> str:
    domain = str(source.get("source") or "").lower().removeprefix("www.")
    labels = {
        "apnews.com": "AP News",
        "forbes.com": "Forbes",
        "purplesec.us": "PurpleSec",
        "theconversation.com": "The Conversation",
    }
    return labels.get(domain, domain.split(".")[0].title() if domain else "One source")


def clean_title(title: str) -> str:
    title = re.sub(r"\s+", " ", title).strip().rstrip(".")
    title = re.sub(r"\s+-\s+Forbes$", "", title)
    return title


def load_sources(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def read_optional_text_arg(text_arg: Optional[str], file_arg: Optional[str]) -> Optional[str]:
    if text_arg:
        return text_arg.strip()
    if file_arg:
        path = Path(file_arg).expanduser()
        if not path.is_absolute():
            path = PROJECT_ROOT / path
        return path.read_text(encoding="utf-8").strip()
    return None


def resolve_summarize_prompt(args: argparse.Namespace) -> str:
    prompt = read_optional_text_arg(args.summarize_prompt, args.summarize_prompt_file)
    if prompt:
        return prompt

    env_prompt = os.environ.get("NEWS_SUMMARIZE_PROMPT", "").strip()
    if env_prompt:
        return env_prompt

    env_prompt_file = os.environ.get("NEWS_SUMMARIZE_PROMPT_FILE", "").strip()
    if env_prompt_file:
        path = Path(env_prompt_file).expanduser()
        if not path.is_absolute():
            path = PROJECT_ROOT / path
        prompt = path.read_text(encoding="utf-8").strip()
        if prompt:
            return prompt

    raise SystemExit("Provide --summarize-prompt, --summarize-prompt-file, NEWS_SUMMARIZE_PROMPT, or NEWS_SUMMARIZE_PROMPT_FILE.")


def resolve_intended_video_max_seconds(args: argparse.Namespace) -> Optional[float]:
    if args.intended_video_max_seconds is not None:
        return args.intended_video_max_seconds

    env_value = os.environ.get("NEWS_INTENDED_VIDEO_MAX_SECONDS", "").strip()
    if not env_value:
        return None
    return float(env_value)


def append_timing_guidance(summarize_prompt: str, intended_seconds: Optional[float], wpm: float) -> tuple[str, Optional[int]]:
    if intended_seconds is None:
        return summarize_prompt, None
    if intended_seconds <= 0:
        raise SystemExit("Intended video max seconds must be greater than zero.")
    if wpm <= 0:
        raise SystemExit("WPM must be greater than zero.")

    target_words = max(1, math.floor(intended_seconds * wpm / 60.0))
    guidance = (
        "Video timing guidance: the intended video length is around "
        f"{intended_seconds:g} seconds. At {wpm:g} words per minute that is roughly "
        f"{target_words} spoken words. Aim for that length."
    )
    return f"{summarize_prompt.rstrip()}\n\n{guidance}", target_words


def call_openai_compatible(summarize_prompt: str, user_prompt: str, timeout: int) -> Optional[str]:
    base_url = os.environ.get("OPENAI_BASE_URL", "").strip().rstrip("/")
    api_key = os.environ.get("OPENAI_API_KEY", "").strip()
    model = os.environ.get("OPENAI_MODEL", "").strip()
    if not base_url or not model:
        return None

    requests = importlib.import_module("requests")
    headers = {"Content-Type": "application/json"}
    if api_key:
        headers["Authorization"] = f"Bearer {api_key}"

    payload: dict[str, Any] = {
        "model": model,
        "messages": [
            {"role": "system", "content": summarize_prompt},
            {"role": "user", "content": user_prompt},
        ],
        "stream": False,
        "temperature": 0.2,
    }
    # Reasoning models otherwise spend the whole timeout budget thinking and
    # return an empty script. Only sent when configured, so plain OpenAI-
    # compatible servers that reject the field are unaffected.
    reasoning_effort = os.environ.get("OPENAI_REASONING_EFFORT", "").strip()
    if reasoning_effort:
        payload["reasoning_effort"] = reasoning_effort
    # Context window: Ollama honors options.num_ctx per request (LLM_CONTEXT_SIZE / LLM_CONTEXT_CAP);
    # vLLM and SGLang fix it at launch, so nothing is added for them.
    try:
        from services import llm as llm_context

        payload.update(llm_context.request_options())
    except Exception:  # noqa: BLE001 - never block a script call on context detection
        pass
    response = requests.post(f"{base_url}/chat/completions", headers=headers, json=payload, timeout=timeout)
    response.raise_for_status()
    data = response.json()
    return data["choices"][0]["message"]["content"].strip()


def fallback_script(bundle: dict[str, Any]) -> str:
    subject = humanize_subject(str(bundle.get("subject") or "this issue"))
    sources = bundle.get("selected_sources") or []
    if not sources:
        raise SystemExit("No selected_sources found in source bundle.")

    lead = f"In today's AI briefing, selected SearXNG results on {subject} point to security, governance, and enterprise risk."
    close = "For enterprises, the takeaway is clear: AI adoption now has to move with stronger controls, auditability, and oversight."
    script_sentences = [lead]

    for source in sources[:5]:
        title = clean_title(source.get("title") or "")
        if not title:
            continue
        candidate = f"{source_label(source)} highlights: {title}."
        script_sentences.append(candidate)

    final_script = " ".join([*script_sentences, close])
    return final_script


def default_output_path(sources_path: Path) -> Path:
    return sources_path.with_name("narration.txt")


def write_report(path: Path, bundle: dict[str, Any], script: str, mode: str) -> None:
    report_path = path.with_name("report.md")
    sources = bundle.get("selected_sources") or []
    lines = [
        "# News Script Report",
        "",
        f"Generated: {datetime.now(timezone.utc).isoformat()}",
        f"Subject: {bundle.get('subject', '')}",
        f"Mode: {mode}",
        f"Words: {word_count(script)}",
        "",
        "## Script",
        "",
        script,
        "",
        "## Sources",
        "",
    ]
    for index, source in enumerate(sources, 1):
        lines.append(f"{index}. [{source.get('title', '')}]({source.get('url', '')})")
        if source.get("content"):
            lines.append(f"   - {source.get('content')}")
    report_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate a timed script from selected SearXNG sources.")
    parser.add_argument("--sources", required=True, help="Path to sources.json from search_searxng.py.")
    parser.add_argument("--output", help="Output script path. Defaults beside sources.json.")
    parser.add_argument("--no-llm", action="store_true", help="Skip OpenAI-compatible script generation even if configured.")
    parser.add_argument("--summarize-prompt", help="Override NEWS_SUMMARIZE_PROMPT for this run.")
    parser.add_argument("--summarize-prompt-file", help="Path to a UTF-8 summarize prompt file for this run.")
    parser.add_argument("--intended-video-max-seconds", type=float, help="Append max video length guidance to the summarize prompt.")
    parser.add_argument("--wpm", type=float, default=float(os.environ.get("NEWS_DEFAULT_WPM", "145")), help="Words per minute used for target word count guidance.")
    parser.add_argument("--timeout", type=int, default=int(os.environ.get("OPENAI_DEFAULT_TIMEOUT_SECONDS", "90")), help="LLM HTTP timeout in seconds.")
    return parser.parse_args()


def main() -> None:
    load_env_file(PROJECT_ROOT / ".env")
    args = parse_args()
    sources_path = Path(args.sources).expanduser()
    if not sources_path.is_absolute():
        sources_path = PROJECT_ROOT / sources_path
    output_path = Path(args.output).expanduser() if args.output else default_output_path(sources_path)
    if not output_path.is_absolute():
        output_path = PROJECT_ROOT / output_path

    bundle = load_sources(sources_path)
    summarize_prompt = resolve_summarize_prompt(args)
    intended_seconds = resolve_intended_video_max_seconds(args)
    summarize_prompt, target_words = append_timing_guidance(summarize_prompt, intended_seconds, args.wpm)
    summarize_prompt = prompting.render_prompt_variables(
        summarize_prompt,
        prompting.prompt_variables(bundle, args, intended_seconds, target_words),
    )
    summarize_prompt, user_prompt = prompting.build_prompt(bundle, summarize_prompt)

    mode = "fallback"
    script: Optional[str] = None
    if not args.no_llm:
        try:
            script = call_openai_compatible(summarize_prompt, user_prompt, args.timeout)
        except importlib.import_module("requests").exceptions.RequestException:
            script = None
        if script:
            mode = "openai-compatible"

    if not script:
        script = fallback_script(bundle)
        mode = "fallback"

    script = re.sub(r"\s+", " ", script).strip()
    words = word_count(script)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(script + "\n", encoding="utf-8")
    write_report(output_path, bundle, script, mode)

    print(f"script_path={output_path}")
    print(f"report_path={output_path.with_name('report.md')}")
    print(f"mode={mode}")
    print(f"word_count={words}")
    print(f"intended_video_max_seconds={intended_seconds:g}" if intended_seconds is not None else "intended_video_max_seconds=None")
    print(f"wpm={args.wpm:g}")
    print(f"target_words={target_words}" if target_words is not None else "target_words=None")


if __name__ == "__main__":
    main()
